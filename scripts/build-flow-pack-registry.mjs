function collectPrivateMountPaths(packs) {
  return packs
    .filter((pack) => pack.__visibility === 'private')
    .flatMap((pack) => [
      ...(pack.publicPages ?? []).map((page) => routeToMountFile(page.route, 'page')),
      ...(pack.publicApiRoutes ?? []).map((route) => routeToMountFile(route.route, 'api')),
    ]);
}

function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

function compareByOrder(a, b) {
  return (a.order ?? 0) - (b.order ?? 0) || String(a.id).localeCompare(String(b.id));
}

function stringify(value) {
  return JSON.stringify(value, null, 2);
}

async function readJson(filePath) {
  const raw = await fs.readFile(filePath, 'utf8');
  return JSON.parse(raw);
}

function stripModuleExtension(modulePath) {
  return modulePath.replace(/\.(ts|tsx|js|jsx)$/, '');
}

async function resolveModuleFile(source, packDir, modulePath) {
  const trimmed = String(modulePath ?? '').trim();
  assert(trimmed, 'Pack public module path is required.');

  const candidates = path.extname(trimmed)
    ? [path.resolve(packDir, trimmed)]
    : ['.ts', '.tsx', '.js', '.jsx'].map((extension) =>
        path.resolve(packDir, `${trimmed}${extension}`)
      );

  for (const candidate of candidates) {
    if (await fileExists(candidate)) {
      if (source.kind === 'package') {
        return `${source.packageName}/${stripModuleExtension(trimmed)}`;
      }

      return path.relative(projectRoot, candidate);
    }
  }

  throw new Error(
    `Unable to resolve public module "${trimmed}" inside pack "${path.basename(packDir)}".`
  );
}

async function resolvePublicMounts(source, packDir, entries, kind) {
  if (!Array.isArray(entries)) return [];

  const mounts = [];
  for (const entry of entries) {
    mounts.push({
      ...entry,
      module: await resolveModuleFile(source, packDir, entry.module),
      kind,
    });
  }

  return mounts;
}

async function resolvePackSourceEntries(sources) {
  const entries = [];

  for (const source of sources) {
    if (source.kind === 'directory') {
      if (!(await fileExists(source.absolutePath))) {
        continue;
      }

      const directoryEntries = await fs.readdir(source.absolutePath, { withFileTypes: true });
      for (const entry of directoryEntries) {
        if (!entry.isDirectory()) continue;
        entries.push({
          source,
          packDir: path.join(source.absolutePath, entry.name),
          packName: entry.name,
        });
      }
      continue;
    }

    entries.push({
      source,
      packDir: source.absolutePath,
      packName: source.packageName,
    });
  }

  return entries;
}

async function resolveRuntimeModule(source, packDir, moduleCandidates) {
  for (const modulePath of moduleCandidates) {
    const candidate = path.join(packDir, modulePath);
    if (!(await fileExists(candidate))) continue;

    if (source.kind === 'package') {
      return `${source.packageName}/${stripModuleExtension(modulePath)}`;
    }

    return path.relative(projectRoot, candidate);
  }

  return null;
}

function resolvePackageRoot(packageName) {
  try {
    const packageJsonPath = requireFromProject.resolve(`${packageName}/package.json`);
    return path.dirname(packageJsonPath);
  } catch {
    throw new Error(
      `Configured flow-pack package "${packageName}" is not installed.`
    );
  }
}

async function collectPackDefinitions() {
  const config = await getFlowPackSourceConfig(projectRoot, process.env);
  const publicLocalDirectorySet = new Set(config.publicLocalDirectories);
  const publicPackageNameSet = new Set(config.publicPackageNames);
  const sources = [
    ...config.localDirectories.map((directory) => ({
      kind: 'directory',
      directory,
      absolutePath: path.resolve(projectRoot, directory),
      visibility: publicLocalDirectorySet.has(directory) ? 'public' : 'private',
    })),
    ...config.packageNames.map((packageName) => ({
      kind: 'package',
      packageName,
      absolutePath: resolvePackageRoot(packageName),
      visibility: publicPackageNameSet.has(packageName) ? 'public' : 'private',
    })),
    ...config.publicPackageNames
      .filter((packageName) => !config.packageNames.includes(packageName))
      .map((packageName) => ({
        kind: 'package',
        packageName,
        absolutePath: resolvePackageRoot(packageName),
        visibility: 'public',
      })),
  ];
  const packEntries = await resolvePackSourceEntries(sources);
  const packs = [];

  for (const entry of packEntries) {
    const packFile = path.join(entry.packDir, 'pack.json');
    if (!(await fileExists(packFile))) {
      continue;
    }

    const cardsDir = path.join(entry.packDir, 'cards');
    const pack = await readJson(packFile);
    if (pack.enabled === false) {
      continue;
    }

    assert(await fileExists(cardsDir), `Pack "${entry.packName}" is missing cards directory.`);
    const cardEntries = await fs.readdir(cardsDir, { withFileTypes: true });
    const cards = [];

    for (const cardEntry of cardEntries) {
      if (!cardEntry.isFile() || !cardEntry.name.endsWith('.json')) continue;
      const cardPath = path.join(cardsDir, cardEntry.name);
      const card = await readJson(cardPath);
      cards.push(card);
    }

    cards.sort(compareByOrder);
    packs.push({
      ...pack,
      __visibility: entry.source.visibility,
      __sourceDirectory:
        entry.source.kind === 'directory' ? entry.source.directory : entry.source.packageName,
      publicPages: await resolvePublicMounts(entry.source, entry.packDir, pack.publicPages, 'page'),
      publicApiRoutes: await resolvePublicMounts(entry.source, entry.packDir, pack.publicApiRoutes, 'api'),
      runtime: {
        serverModule: await resolveRuntimeModule(entry.source, entry.packDir, [
          'server/index.ts',
          'server/index.tsx',
          'server/index.js',
          'server/index.jsx',
        ]),
        uiModule: await resolveRuntimeModule(entry.source, entry.packDir, [
          'ui/index.tsx',
          'ui/index.ts',
          'ui/index.jsx',
          'ui/index.js',
        ]),
        mcpModule: pack.mcp?.module
          ? await resolveModuleFile(entry.source, entry.packDir, pack.mcp.module)
          : null,
      },
      cards,
    });
  }

  packs.sort((a, b) => String(a.id).localeCompare(String(b.id)));
  return packs;
}

async function fileExists(filePath) {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}

function validatePackRegistry(packs) {
  assert(packs.length > 0, 'No flow packs found.');

  const seenPackIds = new Set();
  const seenCardIds = new Set();
  const seenCommandIds = new Set();
  const seenPublicPageRoutes = new Set();
  const seenPublicApiRoutes = new Set();
  const seenPublicPageIds = new Set();
  const seenPublicApiIds = new Set();

  for (const pack of packs) {
    assert(typeof pack.id === 'string' && pack.id.trim(), 'Each pack requires an id.');
    assert(!seenPackIds.has(pack.id), `Duplicate pack id "${pack.id}".`);
    seenPackIds.add(pack.id);
    assert(Array.isArray(pack.cards) && pack.cards.length > 0, `Pack "${pack.id}" has no cards.`);
    assert(
      !pack.publicPages || Array.isArray(pack.publicPages),
      `Pack "${pack.id}" publicPages must be an array when provided.`
    );
    assert(
      !pack.publicApiRoutes || Array.isArray(pack.publicApiRoutes),
      `Pack "${pack.id}" publicApiRoutes must be an array when provided.`
    );
    assert(
      !pack.mcp || typeof pack.mcp === 'object',
      `Pack "${pack.id}" mcp must be an object when provided.`
    );
    if (pack.mcp) {
      assert(
        typeof pack.mcp.module === 'string' && pack.mcp.module.trim(),
        `Pack "${pack.id}" mcp.module is required.`
      );
    }

    for (const page of pack.publicPages ?? []) {
      assert(
        typeof page.id === 'string' && page.id.trim(),
        `Pack "${pack.id}" page route "${page.route}" requires an id.`
      );
      assert(
        typeof page.route === 'string' && page.route.startsWith('/') && !page.route.startsWith('/api/'),
        `Pack "${pack.id}" page route must be a non-API absolute path.`
      );
      assert(
        typeof page.module === 'string' && page.module.trim(),
        `Pack "${pack.id}" page route "${page.route}" requires a module.`
      );
      assert(
        !seenPublicPageRoutes.has(page.route),
        `Duplicate public page route "${page.route}".`
      );
      assert(
        !seenPublicPageIds.has(`${pack.id}:${page.id}`),
        `Duplicate public page id "${page.id}" in pack "${pack.id}".`
      );
      seenPublicPageRoutes.add(page.route);
      seenPublicPageIds.add(`${pack.id}:${page.id}`);
    }

    for (const route of pack.publicApiRoutes ?? []) {
      assert(
        typeof route.id === 'string' && route.id.trim(),
        `Pack "${pack.id}" API route "${route.route}" requires an id.`
      );
      assert(
        typeof route.route === 'string' && route.route.startsWith('/api/'),
        `Pack "${pack.id}" API route must start with "/api/".`
      );
      assert(
        typeof route.module === 'string' && route.module.trim(),
        `Pack "${pack.id}" API route "${route.route}" requires a module.`
      );
      assert(
        Array.isArray(route.methods) && route.methods.length > 0,
        `Pack "${pack.id}" API route "${route.route}" requires methods.`
      );
      for (const method of route.methods) {
        assert(
          typeof method === 'string' && HTTP_METHODS.has(method),
          `Pack "${pack.id}" API route "${route.route}" has unsupported method "${method}".`
        );
      }
      assert(
        !seenPublicApiRoutes.has(route.route),
        `Duplicate public API route "${route.route}".`
      );
      assert(
        !seenPublicApiIds.has(`${pack.id}:${route.id}`),
        `Duplicate public API id "${route.id}" in pack "${pack.id}".`
      );
      seenPublicApiRoutes.add(route.route);
      seenPublicApiIds.add(`${pack.id}:${route.id}`);
    }

    for (const card of pack.cards) {
      assert(card.packId === pack.id, `Card "${card.id}" packId must match pack "${pack.id}".`);
      assert(typeof card.id === 'string' && card.id.trim(), 'Each card requires an id.');
      assert(!seenCardIds.has(card.id), `Duplicate card id "${card.id}".`);
      seenCardIds.add(card.id);
      assert(
        typeof card.name?.es === 'string' && typeof card.name?.en === 'string',
        `Card "${card.id}" requires localized names.`
      );
      assert(
        typeof card.description?.es === 'string' && typeof card.description?.en === 'string',
        `Card "${card.id}" requires localized descriptions.`
      );
      assert(
        typeof card.systemPromptByLocale?.es === 'string' &&
          typeof card.systemPromptByLocale?.en === 'string',
        `Card "${card.id}" requires ES/EN system prompts.`
      );
      assert(
        Array.isArray(card.supportedToolIds) && card.supportedToolIds.length > 0,
        `Card "${card.id}" requires supportedToolIds.`
      );
      assert(
        Array.isArray(card.commands),
        `Card "${card.id}" requires commands.`
      );

      const supportedTools = new Set(card.supportedToolIds);
      for (const command of card.commands) {
        assert(
          typeof command.id === 'string' && command.id.trim(),
          `Card "${card.id}" contains a command without id.`
        );
        assert(
          !seenCommandIds.has(command.id),
          `Duplicate command id "${command.id}".`
        );
        seenCommandIds.add(command.id);
        assert(
          supportedTools.has(command.toolId),
          `Command "${command.id}" in card "${card.id}" references unsupported tool "${command.toolId}".`
        );
        assert(
          typeof command.name?.es === 'string' && typeof command.name?.en === 'string',
          `Command "${command.id}" requires localized names.`
        );
        assert(
          typeof command.description?.es === 'string' &&
            typeof command.description?.en === 'string',
          `Command "${command.id}" requires localized descriptions.`
        );
        assert(
          typeof command.category?.es === 'string' && typeof command.category?.en === 'string',
          `Command "${command.id}" requires localized categories.`
        );
        assert(
          typeof command.example?.es === 'string' && typeof command.example?.en === 'string',
          `Command "${command.id}" requires localized examples.`
        );
        assert(
          typeof command.prompt?.es === 'string' && typeof command.prompt?.en === 'string',
          `Command "${command.id}" requires localized prompts.`
        );
        assert(
          Array.isArray(command.aliases?.es) && Array.isArray(command.aliases?.en),
          `Command "${command.id}" requires localized aliases.`
        );
        if (command.iconKey != null) {
          assert(
            typeof command.iconKey === 'string' && command.iconKey.trim(),
            `Command "${command.id}" iconKey must be a non-empty string when provided.`
          );
        }
      }
    }
  }
}

function buildGeneratedPayload(packs) {
  const visiblePacks = packs.map((pack) => {
    const rest = { ...pack };
    delete rest.__visibility;
    delete rest.__sourceDirectory;
    return rest;
  });

  const cards = visiblePacks.flatMap((pack) =>
    pack.cards.map((card) => ({
      ...card,
      commands: [...card.commands].sort(compareByOrder),
    }))
  );
  cards.sort(compareByOrder);

  const commandDefinitions = cards
    .flatMap((card) =>
      card.commands.map((command) => ({
        ...command,
        cardId: card.id,
      }))
    )
    .sort(compareByOrder);

  const flowToolIdsByCard = Object.fromEntries(
    cards.map((card) => [card.id, card.supportedToolIds])
  );
  const cardToCommandIds = Object.fromEntries(
    cards.map((card) => [card.id, card.commands.map((command) => command.id)])
  );
  const menuCommandIds = commandDefinitions
    .filter((command) => command.includeInMenu)
    .map((command) => command.id);
  const commandToBackendTool = Object.fromEntries(
    commandDefinitions.map((command) => [command.id, command.toolId])
  );
  const commandCatalog = Object.fromEntries(
    commandDefinitions.map((command) => [
      command.id,
      {
        es: {
          name: command.name.es,
          description: command.description.es,
          category: command.category.es,
          example: command.example.es,
          prompt: command.prompt.es,
          aliases: command.aliases.es,
          iconKey: command.iconKey ?? null,
        },
        en: {
          name: command.name.en,
          description: command.description.en,
          category: command.category.en,
          example: command.example.en,
          prompt: command.prompt.en,
          aliases: command.aliases.en,
          iconKey: command.iconKey ?? null,
        },
      },
    ])
  );
  const defaultCardSystemPrompts = Object.fromEntries(
    cards.map((card) => [card.id, card.systemPromptByLocale])
  );
  const publicPagesByPack = Object.fromEntries(
    visiblePacks.map((pack) => [
      pack.id,
      Object.fromEntries((pack.publicPages ?? []).map((page) => [page.id, page.route])),
    ])
  );
  const publicApiRoutesByPack = Object.fromEntries(
    visiblePacks.map((pack) => [
      pack.id,
      Object.fromEntries((pack.publicApiRoutes ?? []).map((route) => [route.id, route.route])),
    ])
  );

  return {
    packs: visiblePacks,
    cards,
    commandDefinitions,
    flowToolIdsByCard,
    cardToCommandIds,
    menuCommandIds,
    commandToBackendTool,
    commandCatalog,
    defaultCardSystemPrompts,
    publicPagesByPack,
    publicApiRoutesByPack,
  };
}

