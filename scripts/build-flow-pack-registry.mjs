function renderMcpRuntimeFile(packs) {
  const imports = [];
  const registryEntries = [];

  packs.forEach((pack, index) => {
    if (pack.runtime?.mcpModule && pack.mcp?.module) {
      const alias = `packMcpModule${index}`;
      imports.push({
        alias,
        importPath: toImportPath(outputMcpRuntimeFile, pack.runtime.mcpModule),
      });
      registryEntries.push(
        `  { packId: ${JSON.stringify(pack.id)}, module: ${alias}.mcp satisfies FlowPackMcpModule },`
      );
      return;
    }

    if (pack.runtime?.serverModule && Array.isArray(pack.cards) && pack.cards.length > 0) {
      const alias = `packServerModule${index}`;
      imports.push({
        alias,
        importPath: toImportPath(outputMcpRuntimeFile, pack.runtime.serverModule),
      });
      registryEntries.push(
        `  { packId: ${JSON.stringify(pack.id)}, module: createFlowPackMcpModuleFromServerModule({ cards: ${stringify(pack.cards.map((card) => ({ id: card.id, supportedToolIds: card.supportedToolIds ?? [] })))}, serverModule: ${alias} satisfies FlowPackServerModule }) },`
      );
    }
  });

  const importLines = imports
    .map(({ alias, importPath }) => `import * as ${alias} from '${importPath}';`)
    .join('\n');

  return `// This file is auto-generated by scripts/build-flow-pack-registry.mjs.
// Do not edit manually.
import { createFlowPackMcpModuleFromServerModule, type FlowPackMcpRegistryEntry, type FlowPackMcpModule } from '../lib/platform/pack-mcp';
import type { FlowPackServerModule } from '../lib/platform/pack-server';
${importLines ? `\n${importLines}\n` : ''}
export const GENERATED_FLOW_PACK_MCP_MODULES: readonly FlowPackMcpRegistryEntry[] = [
${registryEntries.join('\n')}
];
`;
}

function renderStyleSourcesFile(packs) {
  const sourceLines = [...new Set(
    packs
      .map((pack) => pack.__sourceDirectory)
      .filter((sourceDirectory) => typeof sourceDirectory === 'string' && sourceDirectory.trim())
      .map((sourceDirectory) => `@source "../../${sourceDirectory}";`)
  )].sort();

  return `/* This file is auto-generated by scripts/build-flow-pack-registry.mjs. */
/* Do not edit manually. */

${sourceLines.join('\n')}
`;
}

function routeToMountFile(route, kind) {
  const normalized = route.replace(/^\/+/, '');
  assert(normalized.length > 0, 'Root-level flow-pack mounts are not supported.');
  return path.join(generatedMountsDir, normalized, kind === 'page' ? 'page.tsx' : 'route.ts');
}

function renderPageMountFile(importPath) {
  return `${GENERATED_MOUNT_MARKER}
// Do not edit manually.

export { default } from '${importPath}';
`;
}

function renderApiMountFile(importPath, methods) {
  const exportList = methods.join(', ');
  return `${GENERATED_MOUNT_MARKER}
// Do not edit manually.

export { ${exportList} } from '${importPath}';
`;
}

async function removeGeneratedMountFiles() {
  async function walk(directory) {
    const entries = await fs.readdir(directory, { withFileTypes: true });
    for (const entry of entries) {
      const absolutePath = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        await walk(absolutePath);
        continue;
      }
      if (!entry.isFile()) continue;
      if (entry.name !== 'page.tsx' && entry.name !== 'route.ts') continue;

      const source = await fs.readFile(absolutePath, 'utf8');
      if (!source.startsWith(GENERATED_MOUNT_MARKER)) continue;
      await fs.unlink(absolutePath);
    }
  }

  if (!(await fileExists(appDir))) return;
  await walk(appDir);
}

async function writePublicMounts(packs) {
  await removeGeneratedMountFiles();

  for (const pack of packs) {
    for (const page of pack.publicPages ?? []) {
      const outputPath = routeToMountFile(page.route, 'page');
      const importPath = toImportPath(outputPath, page.module);
      await fs.mkdir(path.dirname(outputPath), { recursive: true });
      await fs.writeFile(outputPath, renderPageMountFile(importPath), 'utf8');
    }

    for (const route of pack.publicApiRoutes ?? []) {
      const outputPath = routeToMountFile(route.route, 'api');
      const importPath = toImportPath(outputPath, route.module);
      await fs.mkdir(path.dirname(outputPath), { recursive: true });
      await fs.writeFile(outputPath, renderApiMountFile(importPath, route.methods), 'utf8');
    }
  }
}

async function resolveGitDirectory() {
  try {
    const { stdout } = await execFile('git', ['rev-parse', '--git-dir'], { cwd: projectRoot });
    const gitDir = stdout.trim();
    if (!gitDir) return null;
    return path.resolve(projectRoot, gitDir);
  } catch {
    return null;
  }
}

async function updatePrivateMountExcludePaths(packs) {
  const gitDir = await resolveGitDirectory();
  if (!gitDir) {
    return;
  }

  const excludePath = path.join(gitDir, 'info', 'exclude');
  let current = '';
  try {
    current = await fs.readFile(excludePath, 'utf8');
  } catch {
    current = '';
  }

  const privateMountPaths = collectPrivateMountPaths(packs)
    .map((filePath) => `/${path.relative(projectRoot, filePath).split(path.sep).join('/')}`)
    .sort();

  const block = privateMountPaths.length
    ? `${GIT_EXCLUDE_MARKER_START}\n${privateMountPaths.join('\n')}\n${GIT_EXCLUDE_MARKER_END}`
    : '';
  const pattern = new RegExp(
    `\n?${GIT_EXCLUDE_MARKER_START}[\\s\\S]*?${GIT_EXCLUDE_MARKER_END}\n?`,
    'g'
  );
  const cleaned = current.replace(pattern, '').trimEnd();
  const next = block ? `${cleaned ? `${cleaned}\n` : ''}${block}\n` : `${cleaned}${cleaned ? '\n' : ''}`;

  await fs.mkdir(path.dirname(excludePath), { recursive: true });
  await fs.writeFile(excludePath, next, 'utf8');
}

async function resolveTrackedGitPaths(filePaths) {
  if (filePaths.length === 0) {
    return [];
  }

  try {
    const relativePaths = filePaths.map((filePath) => path.relative(projectRoot, filePath));
    const { stdout } = await execFile('git', ['ls-files', '--', ...relativePaths], {
      cwd: projectRoot,
    });

    return stdout
      .split('\n')
      .map((entry) => entry.trim())
      .filter(Boolean);
  } catch {
    return [];
  }
}

async function setGeneratedFilesSkipWorktree(packs, enabled) {
  const gitDir = await resolveGitDirectory();
  if (!gitDir) {
    return;
  }

  const trackedPaths = await resolveTrackedGitPaths([
    ...TRACKED_GENERATED_FILES,
    ...collectPrivateMountPaths(packs),
  ]);

  if (trackedPaths.length === 0) {
    return;
  }

  for (const trackedPath of trackedPaths) {
    const args = [
      'update-index',
      enabled ? '--skip-worktree' : '--no-skip-worktree',
      '--',
      trackedPath,
    ];
    try {
      await execFile('git', args, { cwd: projectRoot });
    } catch (error) {
      console.warn(
        `Warning: unable to update git skip-worktree flag for ${trackedPath}: ${
          error instanceof Error ? error.message : String(error)
        }`
      );
    }
  }
}

async function main() {
  const packs = await collectPackDefinitions();
  validatePackRegistry(packs);
  const payload = buildGeneratedPayload(packs);
  const source = renderGeneratedFile(payload);
  const runtimePacks = payload.packs;
  const serverRuntimeSource = renderServerRuntimeFile(runtimePacks);
  const uiRuntimeSource = renderUiRuntimeFile(runtimePacks);
  const mcpRuntimeSource = renderMcpRuntimeFile(runtimePacks);
  const styleSourcesSource = renderStyleSourcesFile(packs);
  await fs.writeFile(outputFile, source, 'utf8');
  await fs.writeFile(outputServerRuntimeFile, serverRuntimeSource, 'utf8');
  await fs.writeFile(outputUiRuntimeFile, uiRuntimeSource, 'utf8');
  await fs.writeFile(outputMcpRuntimeFile, mcpRuntimeSource, 'utf8');
  await fs.writeFile(outputStyleSourcesFile, styleSourcesSource, 'utf8');
  await writePublicMounts(packs);
  const hasPrivatePacks = packs.some((pack) => pack.__visibility === 'private');
  await updatePrivateMountExcludePaths(packs);
  await setGeneratedFilesSkipWorktree(packs, hasPrivatePacks);
  if (hasPrivatePacks) {
    console.log('Loaded private flow packs from local overlay directories.');
  }
  console.log(`Generated flow pack registry at ${path.relative(projectRoot, outputFile)}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
