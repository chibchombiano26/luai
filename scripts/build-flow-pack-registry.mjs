function toImportPath(fromFile, targetPath) {
  const resolvedLocalPath = path.resolve(projectRoot, targetPath);
  if (!fsSync.existsSync(resolvedLocalPath)) {
    return targetPath;
  }

  const relativePath = path.relative(path.dirname(fromFile), path.resolve(projectRoot, targetPath));
  const withoutExtension = relativePath.replace(/\.(ts|tsx|js|jsx)$/, '');
  const normalized = withoutExtension.split(path.sep).join('/');
  return normalized.startsWith('.') ? normalized : `./${normalized}`;
}

function renderServerRuntimeFile(packs) {
  const imports = packs
    .filter((pack) => pack.runtime?.serverModule)
    .map((pack, index) => {
      const alias = `packServerModule${index}`;
      const importPath = toImportPath(outputServerRuntimeFile, pack.runtime.serverModule);
      return { alias, importPath, packId: pack.id };
    });

  const importLines = imports
    .map(({ alias, importPath }) => `import * as ${alias} from '${importPath}';`)
    .join('\n');

  const registryEntries = imports
    .map(({ alias, packId }) => `  ${JSON.stringify(packId)}: ${alias},`)
    .join('\n');

  return `// This file is auto-generated by scripts/build-flow-pack-registry.mjs.
// Do not edit manually.

import type { FlowPackServerModule } from './pack-server';
${importLines ? `\n${importLines}\n` : ''}
export const GENERATED_FLOW_PACK_SERVER_MODULES: Record<string, FlowPackServerModule> = {
${registryEntries}
};
`;
}

